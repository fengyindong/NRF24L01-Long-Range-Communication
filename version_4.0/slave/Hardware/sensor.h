#ifndef SENSORS_H
#define SENSORS_H

#include <stdint.h>

/* ============================================================
 * 传感器驱动接口（AHT20 温湿度 + BMP280 气压）
 *
 * 本模块负责：
 *   - 初始化 I2C 总线并探测 AHT20、BMP280
 *   - 按周期或按请求触发采样
 *   - 执行温湿度、气压的读取与补偿计算
 *   - 维护一份最近一次的完整快照
 *
 * 状态机设计为非阻塞：
 *   - sensors_task() 分两次调用完成一轮采样
 *   - 第一次触发测量，第二次（等 85ms 后）读取结果
 *   - 等待期间主循环可以继续处理无线等其他任务
 * ============================================================ */

/* ============================================================
 * 数据结构
 * ============================================================ */

/**
 * @brief 传感器数据快照。
 *
 * 每次采样完成后整体更新一次。所有数值均为定点整数，
 * 便于通过 nRF24 无线发送，避免浮点开销。
 */
typedef struct {
    int16_t  temperature_centi_c; /* 温度，单位：0.01℃ */
    uint16_t humidity_centi_rh;   /* 湿度，单位：0.01%RH */
    uint32_t pressure_pa;         /* 气压，单位：Pa */
    uint8_t  status;              /* 传感器状态位（SENSOR_xxx） */
    uint32_t sampled_at_ms;       /* 本次采样完成的时间戳（毫秒） */
} SensorSnapshot;

/* ============================================================
 * 初始化
 * ============================================================ */

/**
 * @brief 初始化 I2C 总线并探测 AHT20、BMP280。
 *
 * 内部流程：
 *   1) 初始化 I2C 总线，并尝试一次总线恢复；
 *   2) 探测 AHT20（地址固定为 0x38）；
 *   3) 依次尝试 BMP280 主地址 0x76 和备用地址 0x77。
 *
 * 探测结果会保存在模块内部，可通过 sensors_aht_address_ok()
 * 和 sensors_bmp_address() 查询。
 */
void sensors_init(void);

/* ============================================================
 * 采集任务
 * ============================================================ */

/**
 * @brief 推进非阻塞采集状态机。
 *
 * 需在主循环中频繁调用，例如：
 *   for (;;) {
 *       sensors_task(millis());
 *       // 其他任务
 *   }
 *
 * 状态机流程：
 *   - IDLE         ：检查是否到采样时间或收到强制采样请求，
 *                    触发 AHT20 和 BMP280 后切到 WAIT_AHT
 *   - WAIT_AHT     ：等到 85ms 转换完成后读取并更新快照，
 *                    设置下次采样时间后回到 IDLE
 *
 * @param now_ms 当前毫秒时间（来自 millis()）
 */
void sensors_task(uint32_t now_ms);

/**
 * @brief 请求尽快执行一次新采样。
 *
 * 如果当前正在测量，会把请求延后到下一轮 IDLE 状态执行。
 */
void sensors_force_sample(void);

/* ============================================================
 * 采样周期
 * ============================================================ */

/**
 * @brief 设置采样周期。
 *
 * 调用方（命令业务层）负责做范围校验，例如限制在
 * APP_MIN_SAMPLE_MS ~ APP_MAX_SAMPLE_MS 之间。
 *
 * @param period_ms 采样周期（毫秒）
 */
void sensors_set_period(uint32_t period_ms);

/**
 * @brief 读取当前采样周期。
 *
 * @return 采样周期（毫秒）
 */
uint32_t sensors_get_period(void);

/* ============================================================
 * 数据读取
 * ============================================================ */

/**
 * @brief 复制最近一次完整数据快照到调用者提供的结构体中。
 *
 * 使用复制而不是返回指针，可以避免调用者直接访问模块内部状态，
 * 也方便在无线发送前获得一份一致的快照。
 *
 * @param out 输出结构体指针
 */
void sensors_get_snapshot(SensorSnapshot *out);

/* ============================================================
 * 探测结果查询（调试用）
 * ============================================================ */

/**
 * @brief 返回 AHT20 最近一次探测/通信是否正常。
 *
 * @return 1 表示正常；0 表示探测失败或最近通信异常
 */
uint8_t sensors_aht_address_ok(void);

/**
 * @brief 返回探测到的 BMP280 地址。
 *
 * @return 0x76 或 0x77 表示探测成功；0 表示未探测到
 */
uint8_t sensors_bmp_address(void);

#endif /* SENSORS_H */