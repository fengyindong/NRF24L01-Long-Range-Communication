#ifndef APP_CONFIG_H
#define APP_CONFIG_H

#include <stdint.h>

/* ============================================================
 * 节点与采样配置
 * ============================================================ */

/* 节点 ID：每块从机烧录前修改，范围 1~254；
 * 主机（网关）的节点表必须包含相同的 ID，否则无法通信。 */
#define APP_NODE_ID                 1u

/* 默认采样周期（毫秒） */
#define APP_DEFAULT_SAMPLE_MS       5000u

/* 采样周期下限（毫秒），由命令设置时校验 */
#define APP_MIN_SAMPLE_MS           1000u

/* 采样周期上限（毫秒），由命令设置时校验 */
#define APP_MAX_SAMPLE_MS           60000u

/* 主机丢失判定时间（毫秒）：
 * 超过此时间未收到主机帧，则在遥测数据中置位 SENSOR_MASTER_LOST。 */
#define APP_MASTER_LOST_MS          30000u

/* 收到主机帧后等待回包的转向时间（毫秒）：
 * 等主机结束自动重发并切换到 PRX 后，从机再发送响应，
 * 避免双方同时处于发射状态导致冲突。 */
#define APP_RESPONSE_TURNAROUND_MS  20u

/* 调试输出开关：1=使能调试日志；0=关闭，节省 CPU 与 Flash */
#define APP_DEBUG_ENABLED           1u

/* 从机固件版本号，仅用于日志显示 */
#define APP_FW_VERSION              "version-4.0"

/* ============================================================
 * 继电器配置
 * ============================================================ */

/* 继电器逻辑状态：1=打开，0=关闭；
 * RELAY_ACTIVE_HIGH=1 表示高电平吸合；=0 表示低电平吸合。 */
#define RELAY_ACTIVE_HIGH           0u

/* ============================================================
 * nRF24L01 射频配置
 *
 * 必须与 F407 主机保持一致：250kbps + 最大功率。
 * ============================================================ */

#define NRF_RF_SETUP_VALUE          0x06u

/* ============================================================
 * 传感器 I2C 地址
 * ============================================================ */

/* AHT20 温湿度传感器 I2C 地址（7 位） */
#define AHT20_I2C_ADDRESS           0x38u

/* BMP280 气压传感器主地址（SDO 接地时使用） */
#define BMP280_I2C_ADDRESS_PRIMARY  0x76u

/* BMP280 气压传感器备用地址（SDO 接高电平时使用） */
#define BMP280_I2C_ADDRESS_ALT      0x77u

#endif /* APP_CONFIG_H */