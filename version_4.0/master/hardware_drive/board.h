#ifndef BOARD_H
#define BOARD_H

#include <stdint.h>

/* ============================================================
 * 板级支持包（Board Support Package）
 *
 * 封装与硬件平台相关的基础功能，包括：
 *   - 系统时钟与毫秒计时
 *   - 微秒级延时
 *   - SPI1 收发（用于 nRF24L01）
 *   - nRF24L01 的 CSN / CE 引脚控制
 *   - 调试串口（USART1）输出
 *   - CLM970 串口（USART2）收发与统计
 * ============================================================ */

/* ============================================================
 * 系统初始化与时间
 * ============================================================ */

/**
 * @brief 初始化板级外设（系统时钟、SPI1、调试串口、CLM 串口等）。
 *
 * @return 1 表示初始化成功；0 表示失败。
 */
uint8_t board_init(void);

/**
 * @brief 获取系统启动后的毫秒计数。
 *
 * @return 毫秒数（32 位，约 49 天回绕）。
 */
uint32_t board_millis(void);

/**
 * @brief 微秒级阻塞延时。
 *
 * @param us 延时长度（微秒）。
 */
void board_delay_us(uint32_t us);

/* ============================================================
 * SPI1 接口（用于 nRF24L01）
 * ============================================================ */

/**
 * @brief 通过 SPI1 交换一个字节（全双工）。
 *
 * @param value 要发送的字节。
 * @return 同时钟周期内从 MISO 读到的字节。
 */
uint8_t board_spi1_transfer(uint8_t value);

/* ============================================================
 * nRF24L01 控制引脚
 * ============================================================ */

/**
 * @brief 控制 nRF24 的 CSN 引脚（片选）。
 *
 * @param high 非 0 输出高电平，0 输出低电平。
 */
void board_nrf_csn(uint8_t high);

/**
 * @brief 控制 nRF24 的 CE 引脚（使能）。
 *
 * @param high 非 0 输出高电平，0 输出低电平。
 */
void board_nrf_ce(uint8_t high);

/* ============================================================
 * 调试串口（USART1）
 * ============================================================ */

/**
 * @brief 向调试串口输出以 '\0' 结尾的字符串。
 *
 * @param text 待输出的字符串。
 */
void board_debug_write(const char *text);

/* ============================================================
 * CLM970（4G 模块）串口
 * ============================================================ */

/**
 * @brief 向 CLM970 模块发送指定长度的数据。
 *
 * @param data   数据缓冲区指针。
 * @param length 数据长度（字节）。
 */
void board_clm_write(const uint8_t *data, uint16_t length);

/**
 * @brief 从 CLM970 模块读取一个字节（非阻塞）。
 *
 * @param value 输出参数，存放读到的字节。
 * @return 1 表示读到有效数据；0 表示当前无数据。
 */
uint8_t board_clm_read(uint8_t *value);

/**
 * @brief 获取 CLM970 串口累计接收的字节总数。
 *
 * @return 接收字节计数。
 */
uint32_t board_clm_rx_bytes(void);

/**
 * @brief 获取 CLM970 串口累计发生的错误次数（ORE/FE/NE/PE）。
 *
 * @return 错误计数。
 */
uint32_t board_clm_uart_errors(void);

#endif /* BOARD_H */