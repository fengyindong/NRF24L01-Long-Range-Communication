#ifndef GATEWAY_H
#define GATEWAY_H

/* ============================================================
 * 网关（Gateway）主控接口
 *
 * 该模块负责：
 *   - 初始化网关应用（命令队列、发布队列、节点列表等）
 *   - 处理 nRF24 无线通信（轮询从机、下发命令、接收遥测）
 *   - 管理 MQTT 发布队列，上传遥测与状态
 *   - 处理云端下发的 MQTT 控制命令
 *
 * 典型主循环：
 *   gateway_init();
 *   for (;;) {
 *       clm970_task();            // 4G/MQTT 驱动
 *       gateway_radio_task();     // nRF24 收发
 *       gateway_publish_task();   // MQTT 发布队列
 *   }
 * ============================================================ */

/* ============================================================
 * 初始化与任务
 * ============================================================ */

/**
 * @brief 初始化网关应用。
 *
 * 完成系统初始化后、进入主循环前调用一次。
 * 内部会初始化命令队列、发布队列、各从机节点的轮询时间，
 * 并打印 MQTT 命令解析器版本。
 */
void gateway_init(void);

/**
 * @brief 无线通信任务。
 *
 * 需在主循环中反复调用，内部是非阻塞状态机：
 *   - 空闲时检查是否有待发命令或到期轮询
 *   - 有任务时构造帧并发送，进入等待状态
 *   - 等待状态下轮询接收从机响应，校验并处理
 *   - 超时未响应则回到空闲，稍后重试
 *
 * 负责：
 *   - 轮询从机获取遥测数据
 *   - 向从机下发控制命令
 *   - 处理从机的命令应答
 *   - 维护节点轮询周期
 */
void gateway_radio_task(void);

/**
 * @brief MQTT 发布任务。
 *
 * 需在主循环中反复调用，将发布队列中的消息依次交给 CLM970 驱动
 * 发送。单条发送失败则立即退出，避免阻塞主循环。
 *
 * 负责：
 *   - 将遥测数据、命令回执、继电器状态等上传到 MQTT
 *   - 在 MQTT 连接断开时由 CLM970 驱动自动重连
 */
void gateway_publish_task(void);

/* ============================================================
 * MQTT 下行消息回调
 * ============================================================ */

/**
 * @brief MQTT 下行消息回调。
 *
 * 当 CLM970 收到云端下发的 PUBLISH 消息时，由驱动调用此函数。
 * 内部会解析命令并放入无线命令队列，唤醒无线任务立即下发。
 *
 * 解析失败时会打印详细诊断信息（解析器版本、主题长度、载荷长度、
 * 首尾字节），便于定位 JSON 格式问题。
 *
 * @param topic   消息主题（以 '\0' 结尾）
 * @param payload 消息内容（以 '\0' 结尾）
 */
void gateway_on_mqtt_message(const char *topic, const char *payload);

#endif /* GATEWAY_H */